#!/usr/bin/env node
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const f=x=>readFileSync(new URL('../'+x,import.meta.url),'utf8');
const app=f('apps/admin/src/App.tsx');
const management=f('apps/admin/src/resources/RedemptionManagement.tsx');
const issue=f('apps/admin/src/resources/IssueCodes.tsx');
const provider=f('apps/admin/src/data/dataProvider.ts');
const nav=f('apps/admin/src/resources/domainNavigationModel.ts');
const sql=f('supabase/migrations/20261029195000_redemption_single_use_admin.sql');
const check=(source,re,reason)=>assert.match(source,re,reason);
const absent=(source,re,reason)=>assert.doesNotMatch(source,re,reason);
check(app,/<Resource name="code-batches"[^>]*list=\{BatchesList\} show=\{BatchShow\}/,'only one redemption Resource');
absent(app,/<Resource name="codes"|<Resource name="redemptions"/,'no separate code or redemption views');
absent(nav,/redemption:\{title:'兑换码'/,'no redemption tabs');
check(management,/export function RedemptionBatchesList/,'batch list exists');
check(management,/export function RedemptionBatchShow/,'batch detail exists');
check(management,/className="aisen-admin-list-page"/,'fixed filter and scroll-only data area');
check(management,/<Table stickyHeader/,'sticky table headers');
check(management,/getList|useGetList/,'server-paginated data reads');
check(management,/redeemed_by/,'redeemer shown in batch detail');
check(management,/redeemed_at/,'redeem time shown in batch detail');
check(management,/grant_id/,'grant trace shown in batch detail');
check(management,/!scope&&<TableCell/,'product column only in global view');
check(management,/code_prefix/,'only safe prefix display');
absent(management,/code_hash|full_code/,'no secret code access');
check(issue,/p_max_redemptions_per_code:1/,'single-use issuance fixed at one');
absent(issue,/每码最大核销次数|setUses|maxRedemptions:/,'multi-use input and pending metadata removed');
check(issue,/plaintext_available/,'initial plaintext only');
check(issue,/idempotent_replay/,'no plaintext on replay');
check(provider,/admin_code_batches_v2/,'batch list RPC');
check(provider,/admin_batch_codes_v2/,'batch code detail RPC');
check(sql,/CHECK \(max_redemptions_per_code = 1\)/,'batch level constraint');
check(sql,/CHECK \(max_redemptions = 1 AND redeemed_count IN \(0,1\)\)/,'code level constraint');
check(sql,/UNIQUE \(code_id\)/,'only one redemption fact per code');
check(sql,/p_max_redemptions_per_code<>1/,'private generator rejects multiple uses');
check(sql,/PERFORM private\.require_admin\(\)/,'reads require administrator AAL2');
check(sql,/LEFT JOIN public\.redemptions r ON r\.code_id=c\.id/,'detail joins actual redemption');
check(sql,/p_product_id IS NULL OR b\.product_id=p_product_id/,'scope checks on batches');
check(sql,/SCOPE_MISMATCH/,'detail prevents mismatched product selection');
absent(sql,/code_hash.*jsonb/,'secret hash not returned in RPC');
console.log('REDEMPTION_SINGLE_PAGE_CONTRACT PASS (browser and SQL auth tested separately)');
