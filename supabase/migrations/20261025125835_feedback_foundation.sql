-- FB-01A: feedback relational foundation. Production interfaces NOT YET IMPLEMENTED.
-- All write paths are fail-closed until the protected FB-01B/C RPCs land.
-- AisenCore owns feedback metadata; R2 private objects are separate, not ACID.
CREATE TABLE public.user_feedback (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  feedback_no bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  product_id uuid NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  content text NOT NULL,
  category text NOT NULL DEFAULT 'other',
  status text NOT NULL DEFAULT 'new',
  priority text NOT NULL DEFAULT 'normal',
  assigned_to uuid REFERENCES auth.users(id) ON DELETE RESTRICT,
  request_id uuid NOT NULL,
  version integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
  resolved_at timestamptz,
  closed_at timestamptz,
  CONSTRAINT user_feedback_request_unique UNIQUE (user_id, product_id, request_id),
  CONSTRAINT user_feedback_content_nonempty CHECK (char_length(btrim(content)) BETWEEN 1 AND 20000),
  CONSTRAINT user_feedback_category_valid CHECK (
    category IN ('bug','account','experience','suggestion','other')),
  CONSTRAINT user_feedback_status_valid CHECK (
    status IN ('new','in_progress','waiting_user','resolved','closed')),
  CONSTRAINT user_feedback_priority_valid CHECK (
    priority IN ('low','normal','high','urgent')),
  CONSTRAINT user_feedback_version_positive CHECK (version > 0),
  CONSTRAINT user_feedback_timestamps_valid CHECK (
    (resolved_at IS NULL OR resolved_at >= created_at)
    AND (closed_at IS NULL OR closed_at >= created_at))
);
-- DB length 20,000 is a fail-safe technical ceiling, NOT the unapproved
-- product-facing 5,000-char candidate. Edge limits will be separately frozen.
CREATE INDEX user_feedback_product_status_updated_idx
  ON public.user_feedback(product_id, status, updated_at DESC);
CREATE INDEX user_feedback_updated_idx
  ON public.user_feedback(updated_at DESC);
CREATE INDEX user_feedback_user_created_idx
  ON public.user_feedback(user_id, created_at DESC);

CREATE TABLE public.feedback_attachments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  feedback_id uuid NOT NULL REFERENCES public.user_feedback(id) ON DELETE RESTRICT,
  slot smallint NOT NULL,
  object_key text NOT NULL UNIQUE,
  mime_type text NOT NULL,
  size_bytes bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
  CONSTRAINT feedback_attachment_slot_valid CHECK (slot IN (1,2)),
  CONSTRAINT feedback_attachment_slot_unique UNIQUE (feedback_id, slot),
  CONSTRAINT feedback_attachment_object_key_valid CHECK (
    char_length(object_key) BETWEEN 18 AND 512
    AND object_key LIKE 'feedback/%'),
  CONSTRAINT feedback_attachment_mime_valid CHECK (
    mime_type IN ('image/png','image/jpeg','image/webp')),
  CONSTRAINT feedback_attachment_size_valid CHECK (size_bytes > 0)
);

CREATE TABLE public.feedback_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  feedback_id uuid NOT NULL REFERENCES public.user_feedback(id) ON DELETE RESTRICT,
  actor_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  event_type text NOT NULL,
  visibility text NOT NULL,
  from_status text,
  to_status text,
  message text,
  operation_id uuid,
  created_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
  CONSTRAINT feedback_events_type_valid CHECK (
    event_type IN ('created','status_changed','priority_changed','assigned',
                   'internal_note','public_reply','user_reply')),
  CONSTRAINT feedback_events_visibility_valid CHECK (
    visibility IN ('internal','public')),
  CONSTRAINT feedback_events_from_status_valid CHECK (
    from_status IS NULL OR from_status IN (
      'new','in_progress','waiting_user','resolved','closed')),
  CONSTRAINT feedback_events_to_status_valid CHECK (
    to_status IS NULL OR to_status IN (
      'new','in_progress','waiting_user','resolved','closed')),
  CONSTRAINT feedback_events_message_valid CHECK (
    message IS NULL OR char_length(btrim(message)) BETWEEN 1 AND 20000)
);
CREATE INDEX feedback_events_feedback_created_idx
  ON public.feedback_events(feedback_id, created_at DESC);

-- All tables default-deny. No client insert/update/delete, even if a user
-- constructs a valid object key; user-visible read DTOs come from protected
-- narrow projections/RPCs in FB-01B.
ALTER TABLE public.user_feedback ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.feedback_attachments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.feedback_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.user_feedback, public.feedback_attachments,
  public.feedback_events FROM PUBLIC, anon, authenticated;

-- React-admin's normal list/detail views use the existing AAL2/current-admin
-- test, never the product filter or UI caches as authority.
GRANT SELECT ON public.user_feedback, public.feedback_attachments,
  public.feedback_events TO authenticated;
CREATE POLICY feedback_admin_read ON public.user_feedback
  FOR SELECT TO authenticated USING ((SELECT private.is_platform_admin()));
CREATE POLICY feedback_attachment_admin_read ON public.feedback_attachments
  FOR SELECT TO authenticated USING ((SELECT private.is_platform_admin()));
CREATE POLICY feedback_events_admin_read ON public.feedback_events
  FOR SELECT TO authenticated USING ((SELECT private.is_platform_admin()));

-- Reuse the existing NOLOGIN, narrowly-permissioned function owner.
-- It is not granted to JWT roles and future private functions must independently
-- validate current user/admin privileges before touching any of these rows.
GRANT SELECT, INSERT, UPDATE ON public.user_feedback TO aisencore_rpc_executor;
GRANT SELECT, INSERT ON public.feedback_attachments, public.feedback_events
  TO aisencore_rpc_executor;
CREATE POLICY feedback_rpc_executor ON public.user_feedback
  FOR ALL TO aisencore_rpc_executor USING (true) WITH CHECK (true);
CREATE POLICY feedback_attachment_rpc_executor ON public.feedback_attachments
  FOR ALL TO aisencore_rpc_executor USING (true) WITH CHECK (true);
CREATE POLICY feedback_events_rpc_executor ON public.feedback_events
  FOR ALL TO aisencore_rpc_executor USING (true) WITH CHECK (true);
